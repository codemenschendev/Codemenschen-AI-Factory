// Pages can define their own translations in window.PAGE_DE before this script loads.
Object.assign(DE, window.PAGE_DE || {});

// English strings are inline in the HTML; capture them once so we can toggle back.
const EN = {};
document.querySelectorAll("[data-i18n]").forEach(el => {
  EN[el.dataset.i18n] = el.innerHTML;
});

function setLang(lang) {
  const dict = lang === "de" ? DE : EN;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const t = dict[el.dataset.i18n];
    if (t !== undefined) el.innerHTML = t;
  });
  document.documentElement.lang = lang;
  document.getElementById("langToggle").textContent = lang === "de" ? "EN" : "DE";
  try { localStorage.setItem("appwerk-lang", lang); } catch (e) {}
  currentLang = lang;
}

let currentLang = "en";
let stored = null;
try { stored = localStorage.getItem("appwerk-lang"); } catch (e) {}
const browserLang = (navigator.language || "en").toLowerCase();
const initial = stored || (browserLang.startsWith("de") ? "de" : "en");
if (initial === "de") setLang("de");

document.getElementById("langToggle").addEventListener("click", () => {
  setLang(currentLang === "de" ? "en" : "de");
});

// Scroll-reveal: subtle rise-in, once per element.
const io = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (e.isIntersecting) {
      e.target.classList.add("in");
      io.unobserve(e.target);
    }
  });
}, { threshold: 0.12 });
document.querySelectorAll(".reveal").forEach(el => io.observe(el));
